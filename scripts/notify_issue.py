"""Open (or update) a GitHub issue when a high-score gap shows up.

Reads the newest data/gap/*.json, filters candidates at or above --threshold,
and creates one issue per day. Re-runs on the same day update the existing
issue instead of spamming a new one, so the workflow stays idempotent.

Usage:
    GH_TOKEN=... python scripts/notify_issue.py --threshold 80
    GH_TOKEN=... python scripts/notify_issue.py --threshold 80 --dry-run
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import requests

API = "https://api.github.com"


def newest_gap(folder: Path) -> dict | None:
    files = sorted(folder.glob("*.json"))
    return json.loads(files[-1].read_text(encoding="utf-8")) if files else None


def build_body(gap: dict, hits: list[dict]) -> str:
    lines = [
        f"Snapshot `{gap['date']}` found **{len(hits)} domain(s)** at or above the threshold.",
        "",
        "| Score | Domain | Existing lists | Best existing list | Witness repos |",
        "|---:|---|---:|---|---|",
    ]
    for c in hits:
        best = (
            f"[{c['existing_top_repo']}](https://github.com/{c['existing_top_repo']}) "
            f"({c['existing_top_stars']:,} stars)"
            if c.get("existing_top_repo")
            else "—"
        )
        witnesses = ", ".join(f"`{w}`" for w in c.get("witnesses", [])[:3]) or "—"
        lines.append(
            f"| {c['score']:.1f} | `{c['domain']}` | {c['existing_lists']} | {best} | {witnesses} |"
        )
    lines += [
        "",
        "### How to act on this",
        "",
        "Reply with a number to have the repository scaffolded:",
        "",
    ]
    for i, c in enumerate(hits, 1):
        lines.append(f"{i}. `awesome-{c['domain']}` — score {c['score']:.1f}")
    lines += [
        "",
        "---",
        "_Generated by `scripts/notify_issue.py`. Nothing is created until someone replies._",
    ]
    return "<details open>\n<summary>Candidate domains</summary>\n\n" + "\n".join(lines) + "\n\n</details>"


def find_existing(session: requests.Session, repo: str, title: str) -> dict | None:
    resp = session.get(
        f"{API}/repos/{repo}/issues",
        params={"state": "open", "per_page": 50, "sort": "created", "direction": "desc"},
        timeout=30,
    )
    if resp.status_code != 200:
        return None
    for issue in resp.json():
        if issue.get("title") == title and "pull_request" not in issue:
            return issue
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gapdir", default="data/gap")
    ap.add_argument("--threshold", type=float, default=80.0)
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY"))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    gap = newest_gap(Path(args.gapdir))
    if not gap:
        print("[skip] no gap file")
        return 0

    hits = [c for c in gap.get("candidates", []) if c["score"] >= args.threshold]
    if not hits:
        print(f"[skip] nothing at or above {args.threshold}")
        return 0

    title = f"Gap alert {gap['date']}: {len(hits)} uncovered domain(s)"
    body = build_body(gap, hits)

    if args.dry_run:
        print(f"[dry-run] would open: {title}")
        print(body[:800])
        return 0

    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if not token or not args.repo:
        print("[error] GH_TOKEN and GITHUB_REPOSITORY are required", file=sys.stderr)
        return 2

    session = requests.Session()
    session.headers.update(
        {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "User-Agent": "gap-alert",
        }
    )

    existing = find_existing(session, args.repo, title)
    if existing:
        resp = session.patch(
            f"{API}/repos/{args.repo}/issues/{existing['number']}",
            json={"body": body},
            timeout=30,
        )
        print(f"[updated] issue #{existing['number']} -> {resp.status_code}")
        return 0

    resp = session.post(
        f"{API}/repos/{args.repo}/issues",
        json={"title": title, "body": body, "labels": ["gap-alert"]},
        timeout=30,
    )
    print(f"[created] {resp.status_code} {resp.json().get('html_url', '')}")
    return 0 if resp.status_code < 300 else 1


if __name__ == "__main__":
    raise SystemExit(main())
